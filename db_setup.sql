-- 1. TABELA DE RAÇAS
CREATE TABLE T_RACA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL UNIQUE,
    propensao_doenca VARCHAR2(255),
    expectativa_vida NUMBER,
    cuidados_especiais VARCHAR2(500)
);

-- 2. TABELA DE TUTORES
CREATE TABLE T_TUTOR (
    cpf VARCHAR2(14) PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    telefone VARCHAR2(20),
    email VARCHAR2(100),
    qtd_pets NUMBER DEFAULT 0
);

-- 3. TABELA DE MÉDICOS ESPECIALISTAS
CREATE TABLE T_MEDICO_ESPECIALISTA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    especialidade VARCHAR2(50) -- CLINICO, CARDIO, NEURO, NEFRO, HEMATO, ORTOPEDISTA, NUTRICIONISTA, FISIOTERAPEUTA
);

-- 4. TABELA DE CLÍNICAS
CREATE TABLE T_CLINICA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cnpj VARCHAR2(150) NOT NULL,
    telefone VARCHAR2(20)
);

-- 5. TABELA DE PETS
CREATE TABLE T_PET (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    data_nascimento DATE NOT NULL,
    peso NUMBER(5,2),
    status_longevidade VARCHAR2(500),
    raca_id NUMBER,
    tutor_cpf VARCHAR2(14),
    CONSTRAINT fk_pet_raca FOREIGN KEY (raca_id) REFERENCES T_RACA(id),
    CONSTRAINT fk_pet_tutor FOREIGN KEY (tutor_cpf) REFERENCES T_TUTOR(cpf)
);

-- 6. TABELA DE EVENTOS
CREATE TABLE T_EVENTO (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(50), -- EXAMES, CONSULTA DE ROTINA, VACINAS, etc.
    id_pet NUMBER,
    id_tutor VARCHAR2(14),
    id_medico_especialista NUMBER,
    id_clinica NUMBER,
    CONSTRAINT fk_evento_pet FOREIGN KEY (id_pet) REFERENCES T_PET(id),
    CONSTRAINT fk_evento_tutor FOREIGN KEY (id_tutor) REFERENCES T_TUTOR(cpf),
    CONSTRAINT fk_evento_medico FOREIGN KEY (id_medico_especialista) REFERENCES T_MEDICO_ESPECIALISTA(id),
    CONSTRAINT fk_evento_clinica FOREIGN KEY (id_clinica) REFERENCES T_CLINICA(id)
);

-- 7. TABELA DE HISTÓRICO CLÍNICO
CREATE TABLE T_HISTORICO_CLINICO (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento NUMBER,
    data_evento DATE NOT NULL,
    data_vencimento DATE,
    status VARCHAR2(20), -- REALIZADO, PENDENTE, ATRASADO
    observacoes_ia CLOB,
    CONSTRAINT fk_hist_evento FOREIGN KEY (id_evento) REFERENCES T_EVENTO(id)
);

-- 8. TABELA DE TRATAMENTOS
CREATE TABLE T_TRATAMENTO (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pet NUMBER,
    nome_medicamento VARCHAR2(100),
    frequencia VARCHAR2(50),
    data_inicio DATE,
    data_final DATE,
    CONSTRAINT fk_trata_pet FOREIGN KEY (id_pet) REFERENCES T_PET(id)
);

